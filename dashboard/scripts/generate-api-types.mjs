import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'
import { format, resolveConfig } from 'prettier'
import { fileURLToPath } from 'node:url'

const project = fileURLToPath(new URL('../../', import.meta.url))
const output = fileURLToPath(new URL('../src/generated/api.d.ts', import.meta.url))
const openapi = JSON.parse(
  execFileSync(
    'uv',
    [
      'run',
      'python',
      'manage.py',
      'shell',
      '--verbosity=0',
      '--settings=secondshift.config.settings.test',
      '-c',
      'import json; from secondshift.config.api import api; print(json.dumps(api.get_openapi_schema()))',
    ],
    { cwd: project, encoding: 'utf8' },
  ),
)

const schemas = {}
function includeSchema(name) {
  if (Object.hasOwn(schemas, name)) return
  const schema = openapi.components.schemas[name]
  if (!schema) throw new Error(`Missing OpenAPI schema ${name}`)
  schemas[name] = schema
  for (const [, reference] of JSON.stringify(schema).matchAll(
    /"#\/components\/schemas\/([^"]+)"/g,
  )) {
    includeSchema(reference)
  }
}
for (const name of [
  'RunSchema',
  'RunDetailSchema',
  'RunPageSchema',
  'JobSchema',
  'JobDetailSchema',
  'TriggerChangeSchema',
  'RepositorySchema',
  'RepositoryDetailSchema',
  'LocalRepositoryDirectoryListSchema',
  'GitHubAppStatusSchema',
  'SkillInspectionSchema',
  'ConnectionSchema',
  'ConnectionTestSchema',
  'MCPProviderSchema',
  'MCPInspectResultSchema',
  'WebhookSampleSchema',
  'AgentConnectionSchema',
  'ExecutionConfigurationSchema',
  'ExecutionStatusSchema',
  'APISpecSummarySchema',
  'UserSchema',
  'WorkspaceChoiceSchema',
  'WorkspaceSettingsSchema',
  'RunLimitsUpdateSchema',
  'MemberSchema',
  'NewInviteSchema',
  'InviteSchema',
  'PendingInviteSchema',
  'ApiTokenListSchema',
  'NewApiTokenSchema',
  'ApiTokenCreateSchema',
]) {
  includeSchema(name)
}

const ast = await openapiTS({
  openapi: openapi.openapi,
  info: openapi.info,
  paths: {},
  components: { schemas },
})
const generated = await format('// Generated by npm run generate:api-types.\n' + astToString(ast), {
  ...(await resolveConfig(output)),
  filepath: output,
})

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) {
    throw new Error('API types are stale. Run npm run generate:api-types.')
  }
} else {
  writeFileSync(output, generated)
}
